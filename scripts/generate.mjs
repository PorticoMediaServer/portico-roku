// ── Ed25519 constants ───────────────────────────────────────────────────────────────────────
// The curve's constants as sixteen 16-bit limbs (little-endian), computed here rather than typed:
// d = −121665/121666, 2d, the base point (y = 4/5, x even), √−1, and the group order L as bytes.
{
  const P = 2n ** 255n - 19n;
  const mod = v => ((v % P) + P) % P;
  const pow = (b, e) => { let r = 1n; b = mod(b); while (e > 0n) { if (e & 1n) r = mod(r * b); b = mod(b * b); e >>= 1n; } return r; };
  const inv = v => pow(v, P - 2n);
  const D = mod(-121665n * inv(121666n));
  const I = pow(2n, (P - 1n) / 4n);
  const Y = mod(4n * inv(5n));
  const xx = mod((Y * Y - 1n) * inv(D * Y * Y + 1n));
  let X = pow(xx, (P + 3n) / 8n);
  if (mod(X * X) !== xx) X = mod(X * I);
  if (mod(X * X) !== xx) fail('Ed25519: no base point');
  if (X & 1n) X = P - X;
  const L = 2n ** 252n + 27742317777372353535851937790883648493n;
  const limbs = v => Array.from({length: 16}, (_, i) => Number((v >> BigInt(16 * i)) & 0xffffn));
  const bytes = v => Array.from({length: 32}, (_, i) => Number((v >> BigInt(8 * i)) & 0xffn));
  const doubles = list => `[${list.map(n => `${n}#`).join(', ')}]`;
  out('source/core/Ed25519Constants.bs', `${banner('the definition of Curve25519 (computed in scripts/generate.mjs)')}
function Ed25519D() as object
    return ${doubles(limbs(D))}
end function

function Ed25519D2() as object
    return ${doubles(limbs(mod(2n * D)))}
end function

function Ed25519X() as object
    return ${doubles(limbs(X))}
end function

function Ed25519Y() as object
    return ${doubles(limbs(Y))}
end function

function Ed25519I() as object
    return ${doubles(limbs(I))}
end function

function Ed25519L() as object
    return ${doubles(bytes(L))}
end function
`);
}

