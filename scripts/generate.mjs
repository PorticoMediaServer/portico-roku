/** A font's own line height per unit of size (hhea ascender − descender + lineGap, over unitsPerEm). */
function naturalLine(weight) {
  const ttf = readFileSync(join(native, 'assets', fontFile(weight)));
  const tables = {};
  for (let i = 0; i < ttf.readUInt16BE(4); i++) tables[ttf.toString('latin1', 12 + i * 16, 16 + i * 16)] = ttf.readUInt32BE(20 + i * 16);
  if (tables.head === undefined || tables.hhea === undefined) fail(`${fontFile(weight)}: no head or hhea table`);
  const unitsPerEm = ttf.readUInt16BE(tables.head + 18);
  return (ttf.readInt16BE(tables.hhea + 4) - ttf.readInt16BE(tables.hhea + 6) + ttf.readInt16BE(tables.hhea + 8)) / unitsPerEm;
}
