function themeLiteral(name) {
  const start = themeSource.indexOf(`const ${name} = {`);
  if (start < 0) fail(`${themePath}: const ${name} is gone`);
  let i = themeSource.indexOf('{', start);
  let depth = 0;
  const from = i;
  for (; i < themeSource.length; i++) {
    if (themeSource[i] === '{') depth++;
    else if (themeSource[i] === '}' && --depth === 0) break;
  }
  const text = themeSource.slice(from, i + 1);
  const line = themeSource.slice(0, start).split('\n').length;
  const value = new Function('targets', 'designRadii', 'tvRadiusMultiplier', `return (${text});`)(design.targets, design.radii, design.tvRadiusMultiplier);
  return {value, line};
}
