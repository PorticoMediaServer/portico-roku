  if (typeof v === 'string') return `"${v.replace(/"/g, '""')}"`;
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(Number(v.toFixed(6)));
  if (typeof v === 'boolean') return v ? 'true' : 'false';
