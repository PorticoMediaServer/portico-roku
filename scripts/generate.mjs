const reserved = new Set(['and', 'box', 'createobject', 'dim', 'each', 'else', 'elseif', 'end', 'endfunction', 'endif', 'endsub', 'endwhile', 'eval', 'exit', 'exitwhile', 'false', 'for', 'function', 'goto', 'if', 'invalid', 'let', 'next', 'not', 'objfun', 'or', 'pos', 'print', 'rem', 'return', 'run', 'step', 'stop', 'sub', 'tab', 'then', 'to', 'true', 'type', 'while', 'in', 'mod', 'as', 'class', 'namespace', 'import', 'const', 'enum', 'new', 'override', 'interface', 'continue', 'try', 'catch', 'throw']);
