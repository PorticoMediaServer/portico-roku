function iconSvg(def, elements, size) {
  const body = elements.map(e => {
    const fill = 'fill' in e && e.fill === 'currentColor' ? ' fill="#fff"' : '';
    const stroke = 'stroke' in e && e.stroke === 'none' ? ' stroke="none"' : '';
    switch (e.type) {
      case 'path': return `<path d="${e.d}"${fill}${stroke}/>`;
      case 'circle': return `<circle cx="${e.cx}" cy="${e.cy}" r="${e.r}"${fill}${stroke}/>`;
      case 'line': return `<line x1="${e.x1}" y1="${e.y1}" x2="${e.x2}" y2="${e.y2}"/>`;
      case 'rect': return `<rect x="${e.x}" y="${e.y}" width="${e.width}" height="${e.height}"${e.rx ? ` rx="${e.rx}"` : ''}${fill}${stroke}/>`;
      case 'polygon': return `<polygon points="${e.points}"${fill}${stroke}/>`;
      case 'ellipse': return `<ellipse cx="${e.cx}" cy="${e.cy}" rx="${e.rx}" ry="${e.ry}"/>`;
      default: return fail(`icon ${def.id}: unknown element ${e.type}`);
    }
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="${def.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}
