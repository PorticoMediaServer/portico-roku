#!/usr/bin/env node
// Capability tables and actual routes from the checked canonical version-2 producer.
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync, renameSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {stripTypeScriptTypes} from 'node:module';
const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = process.env.PORTICO_SERVER_ROOT;
if (!root) throw new Error('Set PORTICO_SERVER_ROOT to the checkout containing the checked source.');
const pins = JSON.parse(readFileSync(join(app, 'scripts/transport-source-pins.json'), 'utf8'));
const source = {};
for (const [name, hash] of Object.entries(pins.files)) {
  const bytes = execFileSync('git', ['show', `${pins.commit}:${name}`], {cwd: root, maxBuffer: 16*1024*1024});
  if (createHash('sha256').update(bytes).digest('hex') !== hash) throw new Error(`Pinned source mismatch: ${name}`);
  source[name] = bytes.toString('utf8');
}
const {rokuDeclaredProfile, capabilityDocumentProblem} = await import('data:text/javascript;base64,' + Buffer.from(stripTypeScriptTypes(source['packages/client-core/src/client-profile.ts'])).toString('base64'));
const bs = v => v == null ? 'invalid' : Array.isArray(v) ? `[${v.map(bs).join(', ')}]` : typeof v === 'object' ? `{${Object.entries(v).filter(([,x]) => x !== undefined).map(([k,x]) => `${JSON.stringify(k)}: ${bs(x)}`).join(', ')}}` : JSON.stringify(v);
const tables = [true, false].map(uhd => {
  const p = rokuDeclaredProfile({uhd});
  if (p.version !== 2 || capabilityDocumentProblem(p)) throw new Error('Invalid canonical Roku capability table.');
  return p;
});
const route = id => {
  const match = new RegExp(`"${id}": "([^"]+)"`).exec(source['packages/contracts/src/routes.ts']);
  if (!match) throw new Error(`Missing canonical route ${id}`);
  return match[1];
};
const paths = {capabilities:'put_device_capabilities',queue:'create_queue',queueHeader:'get_queue',queueAdvance:'advance_queue',queueSegment:'add_queue_segment',queueWindow:'get_queue_window'};
const banner = `' Generated by scripts/generate-transport.mjs from checked ${pins.commit}.\n' Do not edit; source SHA256s are in scripts/transport-source-pins.json.\n`;
const content = banner + `function RokuCapabilityTable(uhd as boolean) as object\n    if uhd then return ${bs(tables[0])}\n    return ${bs(tables[1])}\nend function\n\nnamespace PlaybackRoutes\n${Object.entries(paths).map(([k,v]) => `    const ${k} = ${JSON.stringify(route(v))}`).join('\n')}\nend namespace\n`;
const path = join(app, 'source/core/CapabilityTables.bs');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== content) throw new Error('Run generate:transport.');
} else { const tmp = `${path}.tmp-${process.pid}`; writeFileSync(tmp, content); renameSync(tmp, path); }
console.log('transport generation verified: version 2 and six registered paths');
