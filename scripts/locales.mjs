#!/usr/bin/env node
/**
 * The channel's languages, from packages/i18n in a sibling portico-server checkout
 * (PORTICO_SERVER_ROOT overrides the location):
 *
 *   data/locale/<locale>.json        a translated language's words, by message id: only the messages the
 *                                    channel uses, and only where the channel's English is today's
 *                                    English (so the arguments it passes are the ones translated).
 *                                    A regional variant's file holds just what differs from its base.
 *   source/core/LocaleIndex.bs       which languages have words, each variant's base, and each
 *                                    translated language's date, time, number, list and size forms
 *                                    (read from Intl here, so the channel formats as the apps do)
 *   locale/en_*\/translations.xml     gains the language names the picker shows
 *   source/core/SettingsTables.bs    SettingsLocales(): every language a viewer can choose
 *
 * Roku picks translations.xml by the device's locale and a channel cannot redirect that, so every
 * other language is read from data/ at run time, for the profile's language or the device's.
 * A registered language with no translations yet has no file and reads English, forms included.
 *
 *   node scripts/locales.mjs            write
 *   node scripts/locales.mjs --check    fail when a generated file is out of date
 */
import {existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const serverRoot = process.env.PORTICO_SERVER_ROOT ?? join(app, '..', 'portico-server');
const i18n = join(serverRoot, 'packages/i18n/src');
const {catalogue, enUS, selectableLocales, translatedLocales, variantBase} = {
  ...(await import(join(i18n, 'catalog/index.ts'))),
  ...(await import(join(i18n, 'index.ts'))),
};
await import(join(i18n, 'catalog/bundled.ts'));

const check = process.argv.includes('--check');
let drift = 0;
const wrote = (path, content) => {
  const file = join(app, path);
  const had = existsSync(file) ? readFileSync(file, 'utf8') : undefined;
  if (had === content) return;
  drift++;
  if (check) { console.error(`locales: ${path} is out of date`); return; }
  mkdirSync(dirname(file), {recursive: true});
  writeFileSync(file, content);
};
const fail = why => { console.error(`locales: ${why}`); process.exit(1); };

// ── The messages the channel uses, as its English snapshot has them ──────────────────────────
const unxml = text => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
const xml = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
function readTranslations(folder) {
  const source = readFileSync(join(app, 'locale', folder, 'translations.xml'), 'utf8');
  return new Map([...source.matchAll(/<source>([^<]*)<\/source>\s*<translation>([^<]*)<\/translation>/g)].map(m => [unxml(m[1]), unxml(m[2])]));
}
const english = readTranslations('en_US');
if (english.size < 100) fail('locale/en_US/translations.xml has too few messages to be the channel’s');
const names = Object.keys(enUS).filter(id => id.startsWith('locale.'));

// The language names, in the English files too: the picker names each language in itself.
const englishFolders = {en_US: 'en-US', en_CA: 'en-CA', en_GB: 'en-GB', en_AU: 'en-GB'};
for (const [folder, locale] of Object.entries(englishFolders)) {
  const words = readTranslations(folder);
  for (const id of names) if (!words.has(id)) words.set(id, catalogue(locale)[id] ?? enUS[id]);
  const messages = [...words.keys()].sort().map(id => `        <message>\n            <source>${xml(id)}</source>\n            <translation>${xml(words.get(id))}</translation>\n        </message>`).join('\n');
  wrote(`locale/${folder}/translations.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate.mjs from packages/i18n/src/catalog (${locale}). Do not edit. -->\n<!DOCTYPE TS>\n<TS version="2.0" language="${folder}">\n    <context>\n        <name>default</name>\n${messages}\n    </context>\n</TS>\n`);
}

// ── Each translated language's words ──────────────────────────────────────────────────────────
// A message whose English here is not today's English is left out: the channel passes the old
// arguments, and English (its own) is the safe answer until the channel is regenerated.
const usable = [...english.keys()].filter(id => Object.hasOwn(enUS, id) && english.get(id) === enUS[id] && !id.startsWith('locale.'));
const skipped = [...english.keys()].filter(id => Object.hasOwn(enUS, id) && english.get(id) !== enUS[id]).length;
const withWords = {};
const keep = new Set();
for (const locale of translatedLocales) {
  const words = catalogue(locale);
  const base = variantBase[locale] ? catalogue(variantBase[locale]) : undefined;
  const own = Object.fromEntries(usable.filter(id => words[id] !== undefined && (!base || base[id] !== words[id])).map(id => [id, words[id]]));
  if (Object.keys(own).length) {
    keep.add(`${locale}.json`);
    wrote(`data/locale/${locale}.json`, JSON.stringify(own, Object.keys(own).sort(), 1) + '\n');
  }
  withWords[locale] = Object.keys(own).length;
}
for (const name of existsSync(join(app, 'data/locale')) ? readdirSync(join(app, 'data/locale')) : []) {
  if (keep.has(name)) continue;
  drift++;
  if (check) console.error(`locales: data/locale/${name} has no language behind it`);
  else rmSync(join(app, 'data/locale', name));
}

// ── Forms, from Intl ──────────────────────────────────────────────────────────────────────────
// A template is a list of parts: {s: literal} or {k: "d" | "M" | "y" | "W" | "h" | "m" | "a"}.
const key = {day: 'd', month: 'M', year: 'y', weekday: 'W', hour: 'h', minute: 'm', dayPeriod: 'a'};
// V8's DateTimeFormat.format() writes U+202F as a plain space for the web's sake; formatToParts()
// does not. The apps show format()'s text, so the channel's dates and times do the same.
const parts = (format, date) => format.formatToParts(date).map(p => ({...p, value: p.value.replace(/\u202f/g, ' ')}));
const template = list => list.map(p => (p.type === 'literal' ? {s: p.value} : key[p.type] ? {k: key[p.type]} : {s: p.value}));
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
function dateStyle(locale, options) {
  const format = new Intl.DateTimeFormat(locale, {...options, timeZone: 'UTC'});
  // October 13, 2026 is a Tuesday; the day and year are unambiguous in every locale.
  const sample = parts(format, Date.UTC(2026, 9, 13));
  const out = {t: template(sample)};
  if (sample.some(p => p.type === 'month')) out.m = Array.from({length: 12}, (_, m) => parts(format, Date.UTC(2026, m, 13)).find(p => p.type === 'month').value);
  // October 11, 2026 is a Sunday: the week from there, Sunday first as roDateTime counts.
  if (sample.some(p => p.type === 'weekday')) out.w = Array.from({length: 7}, (_, d) => parts(format, Date.UTC(2026, 9, 11 + d)).find(p => p.type === 'weekday').value);
  for (let m = 0; m < 12; m++) if (!same(template(parts(format, Date.UTC(2026, m, 13))), out.t)) fail(`${locale}: the ${JSON.stringify(options)} pattern changes with the month`);
  return out;
}
function forms(locale) {
  const time = cycle => new Intl.DateTimeFormat(locale, {hour: 'numeric', minute: '2-digit', hourCycle: cycle, timeZone: 'UTC'});
  const morning = parts(time('h23'), Date.UTC(2026, 9, 13, 9, 5));
  const h12 = time('h12');
  const evening = parts(h12, Date.UTC(2026, 9, 13, 21, 5));
  const early = parts(h12, Date.UTC(2026, 9, 13, 9, 5));
  const number = new Intl.NumberFormat(locale);
  const groupOf = n => number.formatToParts(n).find(p => p.type === 'group')?.value ?? '';
  const list = new Intl.ListFormat(locale, {style: 'long', type: 'conjunction'});
  const unit = name => {
    const parts = new Intl.NumberFormat(locale, {style: 'unit', unit: name, unitDisplay: 'short'}).formatToParts(5);
    return {u: parts.find(p => p.type === 'unit').value, before: parts.findIndex(p => p.type === 'unit') < parts.findIndex(p => p.type === 'integer'), gap: parts.find(p => p.type === 'literal')?.value ?? ''};
  };
  return {
    date: {
      medium: dateStyle(locale, {dateStyle: 'medium'}),
      long: dateStyle(locale, {dateStyle: 'long'}),
      dayMonth: dateStyle(locale, {day: 'numeric', month: 'short'}),
      weekday: dateStyle(locale, {weekday: 'long', day: 'numeric', month: 'short'}),
      monthYear: dateStyle(locale, {month: 'long', year: 'numeric'}),
      year: dateStyle(locale, {year: 'numeric'}),
    },
    time24: template(morning),
    pad24: morning.find(p => p.type === 'hour').value.length === 2,
    time12: template(early),
    am: early.find(p => p.type === 'dayPeriod')?.value ?? 'AM',
    pm: evening.find(p => p.type === 'dayPeriod')?.value ?? 'PM',
    hour12: new Intl.DateTimeFormat(locale, {hour: 'numeric'}).resolvedOptions().hour12 === true,
    group: groupOf(12345),
    // Spanish and Polish leave four-digit numbers ungrouped.
    groupFour: groupOf(1234) !== '',
    decimal: number.formatToParts(1.5).find(p => p.type === 'decimal').value,
    pair: list.formatToParts(['A', 'B']).filter(p => p.type === 'literal').map(p => p.value)[0],
    middle: list.formatToParts(['A', 'B', 'C']).filter(p => p.type === 'literal').map(p => p.value)[0],
    last: list.formatToParts(['A', 'B', 'C']).filter(p => p.type === 'literal').map(p => p.value)[1],
    bytes: ['byte', 'kilobyte', 'megabyte', 'gigabyte', 'terabyte'].map(unit),
  };
}

// ── LocaleIndex.bs ────────────────────────────────────────────────────────────────────────────
const bs = v => {
  if (v === null || v === undefined) return 'invalid';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return `[${v.map(bs).join(', ')}]`;
  if (typeof v === 'object') return `{${Object.entries(v).filter(([, x]) => x !== undefined).map(([k, x]) => `${/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `"${k}"`}: ${bs(x)}`).join(', ')}}`;
  return `"${String(v).replace(/"/g, '""')}"`;
};
// A language the channel can read: it has words, or it is a variant whose base has.
const readable = translatedLocales.filter(l => withWords[l] || (variantBase[l] && withWords[variantBase[l]]));
// `lang` is what a tag's language alone matches (Chinese by script); `id` keeps the locale's case,
// which an associative array's keys need not.
const lang = l => (l.startsWith('zh-') ? l.toLowerCase() : l.split('-')[0]);
const index = Object.fromEntries(readable.map(l => [l, {id: l, lang: lang(l), base: variantBase[l] ?? '', words: withWords[l] > 0, forms: forms(l)}]));
wrote('source/core/LocaleIndex.bs', `' Generated by scripts/locales.mjs from packages/i18n (the translated catalogues) and Intl.
' Do not edit: change the source and run \`npm run locales\`.

' The languages with words in data/locale/: each one's base (a regional variant reads its own words,
' then its base's, then English), whether it has a file of its own, and its forms: date patterns
' (parts {s: literal} or {k: d | M | y | W | h | m | a}, with the month and weekday names they
' take), clocks, number separators, list joins and size units.
function LocaleIndex() as object
    return ${bs(index)}
end function
`);

// ── The picker ────────────────────────────────────────────────────────────────────────────────
const settingsPath = join(app, 'source/core/SettingsTables.bs');
const settings = readFileSync(settingsPath, 'utf8');
const pickerList = settings.replace(/(function SettingsLocales\(\) as object\n    return )\[[^\]]*\]/, `$1${bs([...selectableLocales])}`);
if (pickerList === settings && !settings.includes(bs([...selectableLocales]))) fail('source/core/SettingsTables.bs has no SettingsLocales() to update');
wrote('source/core/SettingsTables.bs', pickerList);

if (check && drift) { console.error('run: npm run locales'); process.exit(1); }
console.log(`locales: ${readable.length} readable languages (${Object.entries(withWords).filter(([, n]) => n).map(([l, n]) => `${l} ${n}`).join(', ')}); ${usable.length} messages usable, ${skipped} left English because the channel's English is older`);
